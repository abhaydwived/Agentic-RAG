"""
src/graph_state.py

Defines the state structure for the LangGraph Agentic RAG workflow.
"""

from typing import Annotated, Any, Dict, List, Optional, TypedDict
import operator


class AgentGraphState(TypedDict):
    """
    State definition for the Agentic RAG workflow in LangGraph.

    Attributes:
        input: Original user query.
        chat_history: Prior conversation turns (list of dicts or BaseMessage).
        normalized_query: Cleaned/clarified query after understanding.
        query_intent: Intent classification (e.g., 'rag', 'web_search', 'finance', 'weather', 'wiki', 'multi_tool', 'direct').
        entities: Extracted entities such as tickers, locations, topics, or keywords.
        plan: Planned list of steps/tools to execute.
        tool_results: Execution results keyed by tool name.
        aggregated_context: Synthesized textual context assembled from all executed tools.
        generation: Candidate answer text generated by LLM.
        validation: Verification result dictionary containing status, feedback, and confidence.
        iteration_count: Number of loop iterations for safety and loop prevention.
        max_iterations: Maximum allowed iterations before terminating.
        tools_used: Deduplicated list of tools invoked during the session.
        output: Final verified user-facing response.
        error: Any fatal or recoverable error encountered.
    """
    input: str
    chat_history: List[Any]
    normalized_query: str
    query_intent: str
    entities: Dict[str, Any]
    plan: List[str]
    tool_results: Annotated[Dict[str, Any], operator.or_]
    aggregated_context: str
    generation: str
    validation: Dict[str, Any]
    iteration_count: int
    max_iterations: int
    tools_used: Annotated[List[str], operator.add]
    output: str
    error: Optional[str]

